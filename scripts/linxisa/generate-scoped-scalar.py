"""Generate QEMU scoped Scalar decode rows and witnesses from LinxISA."""

import argparse
import hashlib
import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[2]
CATALOG = Path("isa/v0.59/state/pto_scalar_forms.json")
LINX_REVISION = "2a29daf7ed6ea33c1719c27abd1ac48d2e75b1cd"
CATALOG_SHA256 = "0f9ab05d6a7547d970b8f2a21b158a5b993527df42445ab494ed8acea0462c16"
PTO_LOCK_SHA256 = (
    "a526f6dbbddfe67d349640f19e904c1148a24178b0ec697f4dc360ddac624f34"
)
LENGTHS = {16: 0, 32: 1, 48: 2}


def packed_encoding(parts):
    size = mask = match = 0
    for part in parts:
        mask |= int(part["mask"], 0) << size
        match |= int(part["match"], 0) << size
        size += part["width_bits"]
    return size, mask, match


def render(data):
    provenance = "/* Generated by scripts/linxisa/generate-scoped-scalar.py. */"
    revision = f"/* Canonical LinxISA input: {LINX_REVISION}. */"
    rows = [provenance, revision]
    witnesses = [provenance, revision]
    bases = {row["form_id"]: row for row in data["forms"]}
    carriers = {}
    runtime_forms = 0
    amo_forms = 0
    for row in data["scoped_forms"]:
        carriers.setdefault(row["base_form_id"], []).append(row)
    if len(carriers) != 235 or len(data["scoped_forms"]) != 705:
        raise ValueError("unexpected scoped Scalar inventory")

    for form_id, variants in sorted(carriers.items()):
        base = bases[form_id]
        agu = base.get("agu", {})
        action = agu.get("action")
        address_kind = agu.get("address_kind")
        store = action in {"Store", "StorePair"}
        load = action in {"Load", "LoadPair"}
        amo = base.get("semantic_family") == "AMO"
        runtime = amo or (
            (load or store) and address_kind in {
                "Immediate", "PCRelative", "Register"
            }
        )
        runtime_forms += int(runtime)
        amo_forms += int(amo)
        store_shift = -1
        if store and address_kind == "Register":
            store_shift = agu["offset_scale"]
        length, mask, match = packed_encoding(base["encoding"])
        reserved_mask = 0
        if base["constraints"]:
            constraint, = base["constraints"]
            if constraint != {"field": "SrcRType", "operator": "one-of", "values": [0, 1, 2]}:
                raise ValueError(f"unsupported legality predicate for {form_id}")
            field = next(f for f in base["fields"] if f["name"] == "SrcRType")
            for piece in field["pieces"]:
                reserved_mask |= ((1 << piece["width"]) - 1) << piece["instruction_lsb"]
            if field["width"] != 2 or reserved_mask.bit_count() != 2:
                raise ValueError(f"unsupported SrcRType layout for {form_id}")
        rows.append(
            f'{{ 0x{mask:012x}, 0x{match:012x}, 0x{reserved_mask:012x}, '
            f"{length // 8}, {str(runtime).lower()}, {store_shift}, "
            f'"{form_id}" }},'
        )
        if len(variants) != 3 or {item["scope_code"] for item in variants} != {0, 1, 2}:
            raise ValueError(f"incomplete scopes for {form_id}")
        for row in sorted(variants, key=lambda r: r["scope_code"]):
            width, full_mask, full_match = packed_encoding(row["encoding"])
            scope = row["scope_code"]
            padding = ((1 << 48) - 1) ^ ((1 << length) - 1)
            prefix = 0x001F | (LENGTHS[length] << 10) | (scope << 8)
            if (
                width != 64
                or full_mask != ((mask | padding) << 16) | 0xFFFF
                or full_match != (match << 16) | prefix
                or row["constraints"] != base["constraints"]
                or (reserved_mask and (match & reserved_mask) == reserved_mask)
            ):
                raise ValueError(f"invalid carrier {row['form_id']}")
            witnesses.append(f'{{ 0x{full_match:016x}, {scope}, {length // 8}, "{form_id}" }},')

    if amo_forms != 58:
        raise ValueError(f"expected 58 scoped AMO forms, got {amo_forms}")
    if runtime_forms != 231:
        raise ValueError(
            f"expected 231 load/store and AMO runtime forms, got {runtime_forms}"
        )
    return ("\n".join(rows) + "\n", "\n".join(witnesses) + "\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("linx_dir", type=Path, help="LinxISA checkout at the locked revision")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    path = args.linx_dir / CATALOG
    data = path.read_bytes()
    if hashlib.sha256(data).hexdigest() != CATALOG_SHA256:
        raise SystemExit(f"{path} must come from LinxISA {LINX_REVISION}")
    path = args.linx_dir / "isa/v0.59/pto-spec.lock.json"
    lock_data = path.read_bytes()
    if hashlib.sha256(lock_data).hexdigest() != PTO_LOCK_SHA256:
        raise SystemExit(f"{path} must come from LinxISA {LINX_REVISION}")
    lock = json.loads(lock_data)
    keys = ("encoding_abi", "encoding_projection_sha256", "release")
    identity = json.dumps(
        {key: lock[key] for key in keys}, separators=(",", ":")
    )
    outputs = [
        ROOT / "target/linx/scoped_scalar_forms.inc",
        ROOT / "tests/unit/linx-scoped-scalar-witnesses.inc",
        ROOT / "hw/linx/pto_scoped_scalar_identity.inc",
    ]
    descriptor = (
        "/* Generated by scripts/linxisa/generate-scoped-scalar.py. */\n"
    )
    descriptor += "".join(
        json.dumps(identity[start:start + 60]) + "\n"
        for start in range(0, len(identity), 60)
    )
    generated = (*render(json.loads(data)), descriptor)
    for path, expected in zip(outputs, generated, strict=True):
        if args.check:
            if path.read_text(encoding="utf-8") != expected:
                raise SystemExit(f"stale generated scoped Scalar data: {path}")
        else:
            path.write_text(expected, encoding="utf-8")


if __name__ == "__main__":
    main()
